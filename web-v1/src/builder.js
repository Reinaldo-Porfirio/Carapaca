// pose das pernas: phase = ciclo de passada, amp = amplitude (0 parado), crouch = agachamento
export function poseLegs(model, phase = 0, amp = 0, crouch = 0) {
  const A = model.anim; if (!A) return;
  if (A.type === 'biped') {
    let ext = 0;
    for (const [k, off] of [['L', 0], ['R', PI]]) {
      const J = A[k], sw = Math.sin(phase + off) * amp;
      const h = -0.5 - crouch * 0.22 + sw * 0.6, kn = 1.02 + crouch * 0.42 + Math.max(0, Math.cos(phase + off)) * amp * 0.8;
      J.hip.rotation.x = h; J.knee.rotation.x = kn; J.ank.rotation.x = -(h + kn);
      ext = Math.max(ext, A.Lt * Math.cos(h) + A.Ls * Math.cos(h + kn) + 0.52);
    }
    model.body.position.y = ext - (model.hipY - 0.3);
  } else if (A.type === 'reverse') {
    let ext = 0;
    for (const [k, off] of [['L', 0], ['R', PI]]) {
      const J = A[k], sw = Math.sin(phase + off) * amp;
      const h = -0.95 - crouch * 0.2 + sw * 0.5, kn = 1.75 + crouch * 0.3 + Math.max(0, Math.cos(phase + off)) * amp * 0.5, an = -1.15 - crouch * 0.1 - sw * 0.2;
      J.hip.rotation.x = h; J.knee.rotation.x = kn; J.ank.rotation.x = an; J.toe.rotation.x = -(h + kn + an);
      ext = Math.max(ext, 2.05 * Math.cos(h) + 2.55 * Math.cos(h + kn) + 1.25 * Math.cos(h + kn + an) + 0.34);
    }
    model.body.position.y = ext - (model.hipY - 0.25);
  } else if (A.type === 'quad') {
    A.legs.forEach((L, i) => {
      const lift = Math.max(0, Math.sin(phase + (i === 0 || i === 3 ? 0 : PI))) * amp;
      L.u.rotation.x = -0.45 - lift * 0.35 + crouch * 0.12; L.kn.rotation.x = 1.75 + lift * 0.2 - crouch * 0.2; L.ft.rotation.x = -(L.u.rotation.x + L.kn.rotation.x);
      L.sh.rotation.y = L.a + Math.sin(phase + (i === 0 || i === 3 ? 0 : PI) + PI / 2) * amp * 0.18;
    });
    model.body.position.y = -crouch * 0.25;
  }
}

