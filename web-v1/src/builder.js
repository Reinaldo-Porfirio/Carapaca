function coreSlab(def) {
  const v = def.m.v, n = new N('core');
  const W = [3.0, 3.7, 4.1][v], H = [2.7, 2.9, 3.1][v], D = [2.3, 2.7, 3.1][v], hd = D / 2;
  n.dim = { W, H, D };
  n.put('c', cyl(0.72, 0.82, 0.7, 12), [0, 0.35, 0]);
  n.put('k', cyl(0.62, 0.62, 0.3, 12), [0, 0.8, 0]);
  n.put('a', bx(W * 0.6, 0.75, D * 0.78, 0.08), [0, 1.0, 0.05]);
  // peito com glacis inclinado
  n.put('a', prism([[-hd, 1.25], [hd * 0.7, 1.25], [hd, 1.8], [hd * 0.6, H], [-hd * 0.85, H], [-hd, 2.1]], W, 0.1));
  // escotilha do piloto sobre o glacis
  const sl = Math.atan2(hd * 0.4, H - 1.8);
  n.put('b', bx(W * 0.42, 0.95, 0.12, 0.04), [0, (H + 1.8) / 2 + 0.02, hd * 0.8 + 0.06], [-sl, 0, 0]);
  n.put('w', bx(W * 0.3, 0.16, 0.06, 0.02), [0, (H + 1.8) / 2 + 0.28, hd * 0.75 + 0.14], [-sl, 0, 0]);
  n.put('g', bx(W * 0.08, 0.05, 0.05, 0.01), [W * 0.14, (H + 1.8) / 2 + 0.06, hd * 0.79 + 0.14], [-sl, 0, 0]);
  // colar e ombros
  n.put('c', cyl(0.6, 0.7, 0.3, 12), [0, H + 0.08, 0.05]);
  both(s => {
    n.put('c', bx(0.7, 0.9, D * 0.7, 0.08), [s * (W / 2 + 0.2), H - 0.7, 0]);
    n.put('d', cylX(0.42, 0.5, 12), [s * (W / 2 + 0.55), H - 0.65, 0]);
    // entradas de ar laterais
    n.put('b', bx(0.25, 0.8, D * 0.5, 0.05), [s * (W / 2 + 0.02), 1.75, 0.1]);
    vent(n, 'k', [s * (W / 2 + 0.16), 1.75, 0.1], D * 0.4, 0.6, 4, s * 0.5, 'x');
    bolts(n, 'd', [[s * W * 0.42, H - 0.25, hd * 0.66], [s * W * 0.42, 1.5, hd * 0.86], [s * W * 0.2, 1.36, hd * 0.84]], 0.06);
  });
  vent(n, 'k', [0, 1.52, hd * 0.86], W * 0.5, 0.36, 3, -0.6);
  // bloco traseiro
  n.put('c', bx(W * 0.78, 1.5, 0.5, 0.06), [0, 1.9, -hd - 0.1]);
  vent(n, 'k', [0, 2.2, -hd - 0.36], W * 0.6, 0.5, 4, 0.5);
  if (v === 0) { // Quaresma: chaminés, santantônio e remendo soldado
    both(s => { n.put('d', cyl(0.13, 0.13, 1.5, 8), [s * W * 0.36, H + 0.25, -hd - 0.2]); n.put('k', cyl(0.16, 0.16, 0.2, 8), [s * W * 0.36, H + 1.0, -hd - 0.2]); });
    n.put('hz', bx(W * 0.9, 0.22, 0.2, 0.03), [0, 1.3, hd * 0.78]);
    n.put('b', bx(0.9, 0.7, 0.06, 0.01), [-W * 0.26, 2.2, hd * 0.86], [-sl * 0.8, 0, 0.12]);
    rod(n, 'd', [-W * 0.3, H, hd * 0.5], [-W * 0.3, H + 0.35, hd * 0.2], 0.05); rod(n, 'd', [W * 0.3, H, hd * 0.5], [W * 0.3, H + 0.35, hd * 0.2], 0.05); rod(n, 'd', [-W * 0.3, H + 0.35, hd * 0.2], [W * 0.3, H + 0.35, hd * 0.2], 0.05);
  } else { // Haldane-Bräck: nervuras fundidas e olhais de reboque
    both(s => { n.put('a', prism([[-hd * 0.8, H], [hd * 0.5, H], [hd * 0.3, H + 0.28], [-hd * 0.7, H + 0.28]], 0.5, 0.05), [s * W * 0.33, 0, 0]); n.put('d', tor(0.14, 0.045, 6, 10), [s * W * 0.4, 1.38, hd * 0.86], [0, 0, 0]); });
    n.put('b', bx(W * 0.94, 0.3, 0.16, 0.04), [0, 1.34, hd * 0.74]);
    if (v === 2) { n.put('b', prism([[hd * 0.55, 1.8], [hd + 0.25, 1.9], [hd * 0.72, H - 0.1]], W * 0.5, 0.05)); both(s => n.put('a', bx(0.5, 1.2, D * 0.9, 0.1), [s * (W / 2 - 0.1), H - 0.4, -0.1])); }
  }
  decal(n, 'mk' + def.mk, [W * 0.24, 2.2, hd * 0.83], [-sl, 0, 0], 0.9, 0.35);
  decal(n, 'n' + (3 + v * 2), [-W / 2 - 0.565, H - 0.7, 0.2], [0, -PI / 2, 0], 0.4, 0.55);
  decal(n, 'warn', [0, 2.0, -hd - 0.36], [0, PI, 0], 0.8, 0.38);
  coreMounts(n, W, H, D, 0.75);
  return n;
}

